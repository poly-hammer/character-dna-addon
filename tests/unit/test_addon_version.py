"""Version commands synchronize local Cargo files without affecting CI or Core's index."""

# Tests execute the repository script and Git with fixed argument lists in temporary checkouts.
# ruff: noqa: S603, S607

import os
import subprocess
import sys
import tomllib

from pathlib import Path

import pytest


SCRIPT = Path(__file__).resolve().parents[2] / "scripts/pre-commit/check_addon_version.py"
CI_VARIABLES = ("CI", "GITHUB_ACTIONS", "PRE_COMMIT_CI", "RUNNING_CI")
CRATES = ("character-dna-converter", "character-dna-io", "character-dna-py")


def git(repo, *args):
    return subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, timeout=30
    ).stdout.strip()


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def commit_fixture(repo):
    git(repo, "init", "-q")
    git(repo, "add", ".")
    git(
        repo,
        "-c",
        "user.name=Version Test",
        "-c",
        "user.email=test@example.com",
        "-c",
        "commit.gpgsign=false",
        "-c",
        f"core.hooksPath={repo / 'no-hooks'}",
        "commit",
        "-qm",
        "fixture",
    )


@pytest.fixture
def checkout(tmp_path):
    addon = tmp_path / "character-dna-addon"
    base = addon / "src/addons/character_dna"
    write(base / "__init__.py", 'bl_info = {"version": (0, 15, 0)}\n')
    write(base / "blender_manifest.toml", 'version = "0.15.0"\n')
    write(addon / "pyproject.toml", '[project]\nname = "character-dna-addon"\nversion = "0.15.0"\n')
    write(addon / "uv.lock", 'version = 1\n[[package]]\nname = "character-dna-addon"\nversion = "0.15.0"\n')
    commit_fixture(addon)
    return addon


def make_core(addon, *, worktree=False):
    core = addon.parent / "character-dna-core"
    members = ", ".join(f'"crates/{name}"' for name in CRATES)
    write(
        core / "Cargo.toml",
        f"""# Keep workspace settings and comments.
[workspace]
members = [{members}]
[workspace.package]
version = "0.14.0" # release version
edition = "2024"
[workspace.dependencies]
third-party = {{ version = "0.14.0" }}
""",
    )
    for name in CRATES:
        write(core / f"crates/{name}/Cargo.toml", f'[package]\nname = "{name}"\nversion.workspace = true\n')
    lock = "# Automatically generated by Cargo.\nversion = 4\n\n"
    for name in CRATES:
        lock += f'[[package]]\nname = "{name}"\nversion = "0.14.0"\n\n'
    lock += """[[package]]
name = "third-party"
version = "0.14.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "unchanged"
dependencies = ["character-dna-io 0.14.0"]

[[package]]
name = "character-dna-io"
version = "0.14.0"
source = "registry+https://example.com/index"
checksum = "also unchanged"
"""
    write(core / "Cargo.lock", lock)
    commit_fixture(core)
    if worktree:
        # Git supports .git files, including worktrees and separate git dirs.
        git_dir = core.parent / "core-git-directory"
        (core / ".git").rename(git_dir)
        write(core / ".git", f"gitdir: {git_dir.as_posix()}\n")
    return core


def run_version(addon, *args, env=None, expected=0):
    environment = {key: value for key, value in os.environ.items() if key not in CI_VARIABLES}
    environment.update(env or {})
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "character_dna", *args],
        cwd=addon,
        env=environment,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    assert result.returncode == expected, result.stdout + result.stderr
    return result.stdout


def versions(addon):
    base = addon / "src/addons/character_dna"
    return (
        tomllib.loads((base / "blender_manifest.toml").read_text())["version"],
        tomllib.loads((addon / "pyproject.toml").read_text())["project"]["version"],
        tomllib.loads((addon / "uv.lock").read_text())["package"][0]["version"],
    )


def assert_core_version(core, version):
    workspace = tomllib.loads((core / "Cargo.toml").read_text())["workspace"]
    assert workspace["package"]["version"] == version
    assert workspace["dependencies"]["third-party"]["version"] == "0.14.0"
    packages = tomllib.loads((core / "Cargo.lock").read_text())["package"]
    assert {row["name"]: row["version"] for row in packages if "source" not in row} == dict.fromkeys(CRATES, version)
    assert [row["version"] for row in packages if "source" in row] == ["0.14.0", "0.14.0"]
    assert packages[3]["dependencies"] == [f"character-dna-io {version}"]
    assert git(core, "diff", "--cached", "--name-only") == ""


@pytest.mark.parametrize("stage", [False, True])
@pytest.mark.parametrize("worktree", [False, True])
def test_vscode_set_version_syncs_core_without_staging_it(checkout, stage, worktree):
    core = make_core(checkout, worktree=worktree)
    run_version(checkout, "--set-version", "0.15.2", *(["--stage"] if stage else []))
    assert versions(checkout) == ("0.15.2",) * 3
    assert "(0, 15, 2)" in (checkout / "src/addons/character_dna/__init__.py").read_text()
    assert_core_version(core, "0.15.2")
    assert len(git(checkout, "diff", "--cached", "--name-only").splitlines()) == (4 if stage else 0)
    assert 'version = "0.15.2" # release version' in (core / "Cargo.toml").read_text()
    assert git(core, "diff", "--name-only").splitlines() == ["Cargo.lock", "Cargo.toml"]
    before = (core / "Cargo.lock").read_bytes()
    run_version(checkout, "--set-version", "0.15.2")
    assert (core / "Cargo.lock").read_bytes() == before


def test_addon_only_checkout_needs_no_core_or_cargo(checkout):
    run_version(checkout, "--set-version", "0.15.2")
    assert versions(checkout) == ("0.15.2",) * 3


@pytest.mark.parametrize("ci_variable", CI_VARIABLES)
def test_ci_never_reads_or_changes_sibling_core(checkout, ci_variable):
    core = make_core(checkout)
    (core / "Cargo.toml").write_text("intentionally invalid TOML")
    before = (core / "Cargo.lock").read_bytes()
    run_version(checkout, "--set-version", "0.15.2", env={ci_variable: "true"})
    assert versions(checkout) == ("0.15.2",) * 3
    assert (core / "Cargo.toml").read_text() == "intentionally invalid TOML"
    assert (core / "Cargo.lock").read_bytes() == before


def test_hook_bumps_and_stages_addon_but_only_updates_core(checkout):
    core = make_core(checkout)
    write(checkout / "src/addons/character_dna/components/test.py", "# change\n")
    git(checkout, "add", ".")
    run_version(checkout, "--watch", "src/addons/character_dna/**/*.py", env={"CI": "false"})
    assert versions(checkout) == ("0.15.1",) * 3
    assert_core_version(core, "0.15.1")
    assert len(git(checkout, "diff", "--cached", "--name-only").splitlines()) == 5
    run_version(checkout)
    assert versions(checkout) == ("0.15.1",) * 3


def test_hook_syncs_manually_staged_version_without_another_bump(checkout):
    run_version(checkout, "--set-version", "0.16.0", "--stage")
    core = make_core(checkout)
    run_version(checkout)
    assert versions(checkout) == ("0.16.0",) * 3
    assert_core_version(core, "0.16.0")


def test_hook_without_staged_changes_is_read_only_even_with_core(checkout):
    core = make_core(checkout)
    run_version(checkout)
    assert git(checkout, "status", "--porcelain") == ""
    assert git(core, "status", "--porcelain") == ""


@pytest.mark.parametrize("mode", ["set", "hook"])
def test_incomplete_core_fails_before_changing_addon_files(checkout, mode):
    core = make_core(checkout)
    (core / "Cargo.lock").write_text("version = 4\n")
    before = (core / "Cargo.toml").read_bytes()
    if mode == "hook":
        write(checkout / "src/addons/character_dna/components/test.py", "# change\n")
        git(checkout, "add", ".")
    output = run_version(checkout, *(["--set-version", "0.15.2"] if mode == "set" else []), expected=1)
    assert "Missing workspace packages" in output
    assert versions(checkout) == ("0.15.0",) * 3
    assert (core / "Cargo.toml").read_bytes() == before


def test_ci_hook_keeps_existing_auto_bump_behavior_without_touching_core(checkout):
    core = make_core(checkout)
    write(checkout / "src/addons/character_dna/components/test.py", "# change\n")
    git(checkout, "add", ".")
    run_version(checkout, env={"GITHUB_ACTIONS": "true"})
    assert versions(checkout) == ("0.15.1",) * 3
    assert git(core, "status", "--porcelain") == ""
